const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key: string, fallback?: string) => fallback || key,
  translateFood: (name: string) => name,
  translateCategory: (category: string) => category,
  translateSlot: (slot: string) => slot,
  translateStatus: (status: string) => status,
});

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('procare_language');
    return saved === 'ta' || saved === 'en' ? saved : 'en';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('procare_language', lang);
  };

  const t = (key: string, fallback?: string): string => {
    const langDict = dictionary[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    const enDict = dictionary.en;
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return fallback !== undefined ? fallback : key;
  };

  const translateFood = (name: string): string => {
    if (language !== 'ta' || !name) return name;
    const trimmed = name.trim();
    if (foodTranslations[trimmed]) return foodTranslations[trimmed];
    // Case-insensitive lookup
    const foundKey = Object.keys(foodTranslations).find(
      (k) => k.toLowerCase() === trimmed.toLowerCase()
    );
    return foundKey ? foodTranslations[foundKey] : name;
  };

  const translateCategory = (cat: string): string => {
    if (language !== 'ta' || !cat) return cat;
    const trimmed = cat.trim();
    if (categoryTranslations[trimmed]) return categoryTranslations[trimmed];
    const upper = trimmed.toUpperCase();
    if (categoryTranslations[upper]) return categoryTranslations[upper];
    return cat;
  };

  const translateSlot = (slot: string): string => {
    if (language !== 'ta' || !slot) return slot;
    const trimmed = slot.trim();
    return slotTranslations[trimmed] || slot;
  };

  const translateStatus = (status: string): string => {
    if (language !== 'ta' || !status) return status;
    const trimmed = status.trim().toUpperCase().replace(/^[✓⚠️\s]+/, '');
    if (statusTranslations[trimmed]) return statusTranslations[trimmed];
    return status;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        translateFood,
        translateCategory,
        translateSlot,
        translateStatus,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
